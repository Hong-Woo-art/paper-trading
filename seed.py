def main():
    ledger = sim.load_ledger()
    if ledger["trades"]:
        sys.exit("이미 원장이 있어요. seed.py는 최초 1회만 실행합니다.")
    tickers = sorted({t for rows in PLAN.values() for t, *_ in rows})
    quotes, fx = sim.latest_quotes(tickers)
    print(f"환율 {fx:,.2f}원/달러")
    for team, rows in PLAN.items():
        for tk, budget, reason, exit_rule in rows:
            px, pdate = quotes[tk]
            mk = sim.market_of(tk)
            krw_px = px * (fx if mk == "US" else 1)
            fee_rate = sim.CFG["fees"][mk]["buy"]
            qty = int(budget // (krw_px * (1 + fee_rate)))
            if qty < 1:
                print(f"  건너뜀 {team} {tk}: 예산 {budget:,}원으로 1주도 못 삼 (1주 {krw_px:,.0f}원)")
                continue
            sim.execute(ledger, team, "buy", tk, qty, px, pdate, fx, reason, exit_rule)
            print(f"  {team} 매수 {sim.CFG['tickers'][tk]['name']} {qty}주 @ {px:,.2f} ({pdate})")
    sim.save_ledger(ledger)
    for team in PLAN:
        pos, cash = sim.holdings_and_cash(ledger, team)
        print(f"{team}: 현금 {cash:,.0f}원, 보유 {len(pos)}종목")


if __name__ == "__main__":
    main()
